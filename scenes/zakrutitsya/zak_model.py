"""«Закрутится?» — три шестерни z12 (32270, двойные конические, чёрные) в углу под прямым углом. Набор SPIKE Prime 45678.
LDraw: LDU, Y вниз; вперёд (к зрителю) = -Z, вправо = +X. Верх основания — Y = 0. Угол O = (0, -110, 0).
  C: ось вертикальная (вдоль Y), шестерня (0, -90, 0) стоит прямо на роторе среднего мотора — её крутит мотор;
  A: ось вдоль X, шестерня (20, -110, 0); B: ось вдоль Z, шестерня (0, -110, 20).
Смещение 20 LDU (1 шип) и фазы проверены по сеткам LDraw (tools/ldphase.py, обобщённое число обмоток):
  каждая пара сцепляется без взаимопроникновения; все три сразу — при фазах A = B = C = 7,5°;
  пары требуют A + B = A + C = B + C = 15° (mod 30°): мотор повернул C на d -> A и B обязаны повернуться на -d,
  а пара A–B требует противоположных углов. Противоречие: механизм стоит. Люфт ≈ 1–1,5°, дальше зубья упираются
  (при 5° — взаимопроникновение 0,7 LDU, при 8° — 1,3 LDU).
Почему z12, а не z20: у z20 смещение 1,5 шипа, вертикальная шестерня встаёт на полшипа мимо сетки — её нечем подпереть.
Рама:
  основание — панель 11x19 (39369, жёлтая), лёжа;
  средний мотор 54696 стоит на основании ротором вверх, приколот снизу 3 штифтами 2780 (как в «Мальтийском механизме»);
  рамы 5x7 (64179, чёрные) стоят вертикально: FA в плоскости Z = 0, FB в плоскости X = 0, длинной стороной вверх;
  ось A (9L, 60485, серая) проходит через боковые отверстия обоих вертикальных краёв FA на высоте Y = -110, ось B — через FB;
  на осях A и B по 2 втулки 3713 (у шестерни и снаружи рамы), ось выступает за втулку на 1 шип, каждая рама приколота к основанию 3 штифтами в нижнем крае;
  ось C — 2L (32062, красная): шестерня C на роторе, ось на 1 шип в роторе."""
import numpy as np

BLACK, LTGREY, RED, YELLOW, WHITE, AZURE = 0, 71, 4, 14, 15, 322
OY = -110.0
D = 20.0
PH0 = 7.5
I = np.eye(3)
G_BASE = {'A': np.array([[0, 0, 1], [0, 1, 0], [-1, 0, 0]], float),   # лок. Z шестерни/втулки -> мир X
          'B': I.copy(),                                               # -> мир Z
          'C': np.array([[1, 0, 0], [0, 0, 1], [0, -1, 0]], float)}    # -> мир Y
A_BASE = {'A': I.copy(),                                               # лок. X оси -> мир X
          'B': np.array([[0, 0, -1], [0, 1, 0], [1, 0, 0]], float),    # -> мир Z
          'C': np.array([[0, -1, 0], [1, 0, 0], [0, 0, 1]], float)}    # -> мир Y
AX = {'A': np.array([1.0, 0, 0]), 'B': np.array([0, 0, 1.0]), 'C': np.array([0, 1.0, 0])}
O = np.array([0, OY, 0])
PIN_V = np.array([[0, -1, 0], [1, 0, 0], [0, 0, 1]], float)            # штифт: лок. X -> мир Y
R_FA = np.array([[1, 0, 0], [0, 0, -1], [0, 1, 0]], float)            # рама: толщина -> Z, длинная сторона -> -Y
R_FB = np.array([[0, 1, 0], [0, 0, 1], [1, 0, 0]], float)             # рама: толщина -> X, длинная сторона -> +Y, 5 -> Z
R_M = np.array([[-1, 0, 0], [0, 1, 0], [0, 0, -1]], float)            # мотор развёрнут: корпус уходит вперёд (-Z)


def rotm(axis, ang):
    a = np.radians(ang); k = axis / np.linalg.norm(axis)
    K = np.array([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
    return I + np.sin(a) * K + (1 - np.cos(a)) * K @ K


def build(dA=0.0, dB=0.0, dC=0.0, shake=(0.0, 0.0, 0.0), b_axle=0.0, b_lift=0.0):
    """dA, dB, dC — повороты от собранной фазы (град, вокруг +X, +Z, +Y). shake — сдвиг всей модели (LDU), дрожь.
    Снятие шестерни B: b_axle — ось B выдвинута назад (+Z, 0..30 LDU: торец уходит из шестерни, но остаётся во внутренней
    втулке, а та упирается в раму и стоит); b_lift — шестерня B поднята вверх (LDU), когда ось из неё вышла."""
    P = []
    sh = np.array(shake, float)

    def add(group, color, part, pos, rot, note):
        P.append(dict(group=group, color=color, part=part, pos=np.array(pos, float) + sh, rot=np.array(rot, float), note=note))

    # ---------- основание ----------
    add('frame', YELLOW, '39369.dat', (60, 10, 0), I, 'основание 11x19')
    # ---------- мотор (корпус неподвижен) ----------
    add('frame', WHITE, 'u9364c01.dat', (0, -30, 0), R_M, 'мотор: корпус')
    for x, z in ((-20, 0), (20, 0), (0, -140)):
        add('frame', BLACK, '2780.dat', (x, 0, z), PIN_V, 'штифт мотор-основание')
    # ---------- рамы ----------
    add('frame', BLACK, '64179.dat', (100, -70, 0), R_FA, 'рама A 5x7')
    add('frame', BLACK, '64179.dat', (0, -70, 100), R_FB, 'рама B 5x7')
    for k in (80, 100, 120):
        add('frame', BLACK, '2780.dat', (k, 0, 0), PIN_V, 'штифт рама A-основание')
        add('frame', BLACK, '2780.dat', (0, 0, k), PIN_V, 'штифт рама B-основание')
    # ---------- C: ротор + ось 2L + шестерня ----------
    RC = rotm(AX['C'], PH0 + dC)
    add('gearC', AZURE, 'u9363p01.dat', (0, -80, 0), rotm(AX['C'], dC) @ R_M, 'мотор: ротор')
    add('gearC', RED, '32062.dat', (0, -80, 0), RC @ A_BASE['C'], 'ось C 2L')
    add('gearC', BLACK, '32270.dat', O + AX['C'] * D, RC @ G_BASE['C'], 'шестерня C z12')
    # ---------- A и B: шестерня, ось 8L, 2 втулки ----------
    for g, dg in (('A', dA), ('B', dB)):
        R = rotm(AX[g], PH0 + dg)
        ax_sh = AX[g] * (b_axle if g == 'B' else 0.0)
        lift = np.array([0, -b_lift, 0]) if g == 'B' else 0.0
        add('gear' + g, BLACK, '32270.dat', O + AX[g] * D + lift, R @ G_BASE[g], f'шестерня {g} z12')
        add('gear' + g, LTGREY, '60485.dat', O + AX[g] * 100 + ax_sh, R @ A_BASE[g], f'ось {g} 9L')
        add('gear' + g, LTGREY, '3713.dat', O + AX[g] * 40, R @ G_BASE[g], f'втулка {g}')
        add('gear' + g, LTGREY, '3713.dat', O + AX[g] * 160 + ax_sh, R @ G_BASE[g], f'втулка {g}')
    return P


if __name__ == '__main__':
    P = build()
    print(len(P), 'деталей')
    from collections import Counter
    for (part, col), n in sorted(Counter((p['part'], p['color']) for p in P).items()):
        print(f'  {n} x {part} цвет {col}')
