if __name__ == '__main__':
    from collections import Counter
    P = build(0)
    cnt = Counter(p['part'] for p in P)
    for k, v in sorted(cnt.items()):
        lim = SET_LIMITS.get(k, '?')
        print(f'{k:14s} {v:3d} / {lim}', '' if lim == '?' or v <= lim else '  <-- ПРЕВЫШЕНО')
    print('деталей:', len(P), '| угол шестерни при открытии:', round(np.degrees(gear_angle(S_OPEN)), 1))
