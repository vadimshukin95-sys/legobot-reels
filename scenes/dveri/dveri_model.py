"""Двери от одной шестерни — модель SPIKE Prime (45678) для рилса «Две двери, одна шестерёнка».
LDraw: LDU, Y вниз; вперёд (к зрителю) = -Z, вправо = +X. Механизм в вертикальной плоскости XY, оси вдоль Z.
Все детали — из набора 45678:
  стенка и задняя плита — 2 панели 11x19 (39369, жёлтые), между ними 2 стойки: ось 8 (3707) + соединители 2L
  (59443) / втулки (3713); средний мотор 54696 приколот спиной к задней плите 3 штифтами, ротор выходит к стенке;
  ось 5 (32073) идёт из ротора через круглое отверстие стенки в шестерню 28 (46372), спереди втулка;
  верхняя рейка 1x13 (64781) зубьями вниз над шестернёй, нижняя — зубьями вверх под ней (межосевое 2 шипа = 35 + 5);
  над верхней рейкой и под нижней — направляющие балки 1x15 (32278), приколоты к стенке;
  каждая рейка двумя штифт-осями 3749 держит «мост» — балку 1x15, а мост двумя штифтами 2780 держит дверь —
  раму 7x11 (39794, маджента). Верхняя рейка везёт правую дверь, нижняя — левую.
Слои по Z: двери [-10, 10], мосты [10, 30], рейки/шестерня/направляющие [30, 50], стенка [50, 70],
мотор [70, 150], задняя плита [150, 170]. Стол: y = 130 (низ стенки, плиты и дверей).
s — ход дверей, LDU: 0 = закрыты, S_OPEN = 120 (6 шипов) = открыты. Шестерня: phi = s / 35 рад (≈196°).
"""
import numpy as np

BLACK, YELLOW, MAGENTA, LTGREY, TAN, WHITE, AZURE = 0, 14, 26, 71, 19, 15, 322
R_GEAR = 35.0
S_OPEN = 120.0

I = np.eye(3)
R_W = np.array([[0, 0, 1], [1, 0, 0], [0, 1, 0]], float)     # панель/балка: лок. Z -> X, лок. X -> Y, отверстия -> Z
R_D = np.array([[1, 0, 0], [0, 0, 1], [0, -1, 0]], float)    # рама двери: лок. Z -> Y, отверстия -> Z
R_PZ = np.array([[0, 0, -1], [0, 1, 0], [1, 0, 0]], float)   # штифт/ось: лок. X -> Z (у 3749 ось +X — назад, в рейку)
R_TOP = np.diag([1.0, -1.0, -1.0])                           # верхняя рейка зубьями вниз


def rz(phi):
    c, s = np.cos(phi), np.sin(phi)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def gear_angle(s):
    """По часовой для зрителя: верх шестерни идёт вправо (+X) вместе с верхней рейкой."""
    return s / R_GEAR


def build(s=0.0):
    P = []

    def add(group, color, part, pos, rot=I, note=''):
        P.append(dict(group=group, color=color, part=part, pos=np.array(pos, float), rot=np.array(rot, float), note=note))

    # ---------- рама: стенка, задняя плита, стойки, направляющие ----------
    add('frame', YELLOW, '39369.dat', (0, 20, 60), R_W, 'стенка 11x19')
    add('frame', YELLOW, '39369.dat', (0, 20, 160), R_W, 'задняя плита 11x19')
    for x in (-160, 160):
        add('frame', BLACK, '3707.dat', (x, 100, 110), R_PZ, 'стойка: ось 8')
        add('frame', LTGREY, '3713.dat', (x, 100, 40), I, 'стойка: втулка перед')
        add('frame', LTGREY, '3713.dat', (x, 100, 180), I, 'стойка: втулка зад')
    add('frame', WHITE, '59443.dat', (-160, 100, 90), I, 'стойка: соединитель 2L')
    add('frame', WHITE, '59443.dat', (-160, 100, 130), I, 'стойка: соединитель 2L')
    add('frame', WHITE, '59443.dat', (160, 100, 90), I, 'стойка: соединитель 2L')
    add('frame', LTGREY, '3713.dat', (160, 100, 120), I, 'стойка: втулка')
    add('frame', LTGREY, '3713.dat', (160, 100, 140), I, 'стойка: втулка')
    for y, nm in ((-60, 'направляющая над верхней рейкой'), (60, 'направляющая под нижней рейкой')):
        add('frame', BLACK, '32278.dat', (0, y, 40), R_W, nm)
        for x in (-140, 140):
            add('frame', BLACK, '2780.dat', (x, y, 50), R_PZ, 'штифт направляющая-стенка')
    # ---------- мотор: корпус приколот к задней плите ----------
    R_M = np.array([[0, 0, 1], [1, 0, 0], [0, 1, 0]], float)  # лок. Z -> X (корпус вправо), лок. -Y -> -Z (ротор к стенке)
    add('frame', WHITE, 'u9364c01.dat', (0, 0, 120), R_M, 'мотор: корпус')
    for pos in ((0, -20, 150), (0, 20, 150), (140, 0, 150)):
        add('frame', BLACK, '2780.dat', pos, R_PZ, 'штифт мотор-плита')
    # ---------- вращается: ротор, ось, шестерня, втулка ----------
    phi = gear_angle(s)
    Rg = rz(phi)
    add('gear', AZURE, 'u9363.dat', (0, 0, 70), Rg @ R_M, 'мотор: ротор')
    add('gear', LTGREY, '32073.dat', (0, 0, 60), Rg @ R_PZ, 'ось 5')
    add('gear', LTGREY, '46372.dat', (0, 0, 40), Rg, 'шестерня 28')
    add('gear', LTGREY, '3713.dat', (0, 0, 20), Rg, 'втулка шестерни')
    # ---------- правая дверь: верхняя рейка едет вправо ----------
    ct = -50 + s
    add('right', BLACK, '64781.dat', (ct, -40, 40), R_TOP, 'верхняя рейка 1x13')
    add('right', BLACK, '32278.dat', (-10 + s, -40, 20), R_W, 'мост правой двери 1x15')
    for x in (ct - 100, ct + 100):
        add('right', TAN, '3749.dat', (x, -40, 30), R_PZ, 'штифт-ось мост-рейка')
    for x in (10 + s, 130 + s):
        add('right', BLACK, '2780.dat', (x, -40, 10), R_PZ, 'штифт дверь-мост')
    add('right', MAGENTA, '39794.dat', (70 + s, 20, 0), R_D, 'правая дверь 7x11')
    # ---------- левая дверь: нижняя рейка едет влево ----------
    cb = 50 - s
    add('left', BLACK, '64781.dat', (cb, 40, 40), I, 'нижняя рейка 1x13')
    add('left', BLACK, '32278.dat', (10 - s, 40, 20), R_W, 'мост левой двери 1x15')
    for x in (cb - 100, cb + 100):
        add('left', TAN, '3749.dat', (x, 40, 30), R_PZ, 'штифт-ось мост-рейка')
    for x in (-130 - s, -10 - s):
        add('left', BLACK, '2780.dat', (x, 40, 10), R_PZ, 'штифт дверь-мост')
    add('left', MAGENTA, '39794.dat', (-70 - s, 20, 0), R_D, 'левая дверь 7x11')
    return P


def write_ldr(parts, path, title='Двери от одной шестерни'):
    def fmt(c, part, pos, R):
        v = list(pos) + list(np.asarray(R).reshape(-1))
        return f'1 {c} ' + ' '.join(f'{x:.4f}'.rstrip('0').rstrip('.') if abs(x) > 1e-9 else '0' for x in v) + f' {part}'
    lines = [f'0 {title}', '0 Name: ' + path.split('/')[-1], '0 Author: LEGObot', '']
    lines += [fmt(p['color'], p['part'], p['pos'], p['rot']) for p in parts]
    open(path, 'w').write('\n'.join(lines) + '\n')


