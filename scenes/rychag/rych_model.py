"""Рычаг-весы LEGObot для рилса «1 груз сильнее трёх?» (детали SPIKE Prime / 9686).
LDraw: LDU, Y вниз; к зрителю = -Z, вправо = +X. Ось вращения — вдоль Z через PIV.
  рама (неподвижно): пластина 6x6, башня из 7 кирпичей 1x2 + техно-кирпич 1x2 с отверстием (ось в его отверстии),
                     ось 6, две втулки;
  beam (качается вокруг PIV): балка 15 (отверстия вдоль Z), за ней T-балка 3x3 на двух штифтах; ось проходит
                     через верхнее отверстие T — на 1 модуль (20 LDU) ВЫШЕ линии балки, поэтому весы устойчивы:
                     при равенстве моментов балка встаёт ровно, при перевесе — наклоняется на угол, а не падает до упора;
  грузы: кирпичи 2x2 на нитках, нитка — петля вокруг балки (может скользить вдоль неё), груз висит вертикально.
Угол равновесия (честная статика без трения): моменты сил тяжести вокруг PIV при повороте балки на theta
  sum w_i*(x_i*cos - A*sin) - M_B*H*sin = 0  =>  tan(theta) = sum(w_i*x_i) / (A*sum(w_i) + M_B*H),
  x_i — плечо груза (LDU, вправо +), A = 29 — низ петли под осью, H = 20 — центр балки под осью,
  M_B — масса балки с T и штифтами в «грузах» (кирпич 2x2 = 1). theta > 0 — правый конец вниз."""
import numpy as np

PIV = np.array([0.0, -20.0, 0.0])
HOLE = 20.0
H = 20.0                    # центр балки под осью
A = 29.0                    # низ петли (точка подвеса нитки) под осью
M_B = 2.6                   # балка 15 + T + 2 штифта ≈ 2,6 кирпича 2x2
STR = 31.0                  # длина нитки от низа петли до шипов груза
N_R, K_R = 3, 2             # справа: 3 груза на 2-м отверстии
FLOOR_Y = 170.0

R_BEAM = np.array([[0, 0, 1], [1, 0, 0], [0, 1, 0.0]])     # 32278: длина -> X, отверстия -> Z
R_T = np.array([[1, 0, 0], [0, 0, 1], [0, -1, 0.0]])        # 60484 (перекладина при z=40, ножка z=0..20): ножка -> вверх, отверстия -> Z
R_ZAX = np.array([[0, 0, -1], [0, 1, 0], [1, 0, 0.0]])      # детали с осью вдоль своего X (ось, штифт) -> вдоль Z
I3 = np.eye(3)


def rz(deg):
    a = np.radians(deg); c, s = np.cos(a), np.sin(a)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1.0]])


def theta_eq(kl):
    """Угол равновесия (град), если слева 1 груз на отверстии kl (может быть дробным — петля скользит)."""
    m = N_R * K_R * HOLE - 1 * kl * HOLE
    return float(np.degrees(np.arctan2(m, A * (N_R + 1) + M_B * H)))


FRAME = [('3958.dat', 27, (0, 162, 50), I3)]
FRAME += [('3004.dat', 15, (0, -6 + 24 * k, 50), I3) for k in range(7)]
FRAME += [('3700.dat', 71, (0, -30, 50), I3),
          ('3706.dat', 72, (0, -20, 50), R_ZAX),
          ('3713.dat', 71, (0, -20, 0), I3),
          ('3713.dat', 71, (0, -20, 70), I3)]
BEAM = [('32278.dat', 322, (0, 0, 0), R_BEAM),
        ('60484.dat', 15, (0, -40, 20), R_T),
        ('2780.dat', 0, (-20, 0, 10), R_ZAX),
        ('2780.dat', 0, (20, 0, 10), R_ZAX)]


def load_parts(n, top):
    """n кирпичей 2x2 стопкой; top — Y шипов верхнего кирпича."""
    return [('3003.dat', 25, (0, top + 4 + 24 * k, 0), I3) for k in range(n)]


def hang(x, th):
    """Точка подвеса (низ петли) для груза с плечом x при наклоне th."""
    return PIV + rz(th) @ np.array([x, A, 0.0])


def build(th, kl):
    """Список деталей: (part, color, pos, rot, group). th — наклон балки, kl — отверстие левого груза."""
    out = []
    for p, c, pos, rot in FRAME:
        out.append((p, c, np.array(pos, float), rot, 'frame'))
    R = rz(th)
    for p, c, pos, rot in BEAM:
        out.append((p, c, PIV + R @ (np.array(pos, float) - PIV), R @ rot, 'beam'))
    for x, n in ((-kl * HOLE, 1), (K_R * HOLE, N_R)):
        s = hang(x, th)
        for p, c, pos, rot in load_parts(n, s[1] + STR):
            out.append((p, c, np.array([s[0], pos[1], 0.0]), rot, 'load'))
        for k in range(1, n):                     # шов между кирпичами стопки (тонкая тёмная полоска)
            out.append(('SEAM', 9999, np.array([s[0], s[1] + STR + 4 + 24 * k, 0.0]), I3, 'load'))
    return out


def strings(th, kl):
    """Нитки: пары (верх, низ) в LDraw."""
    res = []
    for x in (-kl * HOLE, K_R * HOLE):
        s = hang(x, th)
        res.append((s, s + np.array([0, STR, 0])))
    return res


def loops(th, kl):
    """Петли вокруг балки: (центр, матрица поворота балки)."""
    R = rz(th)
    return [(PIV + R @ np.array([x, H, 0.0]), R) for x in (-kl * HOLE, K_R * HOLE)]


def hole_pt(k, th, dz=-12.0):
    """Центр k-го отверстия от оси (k<0 — влево) на передней грани балки."""
    return PIV + rz(th) @ np.array([k * HOLE, H, 0.0]) + np.array([0, 0, dz])


