"""Сценарий петли 12 с «Шлагбаум с датчиком» — общий для 3D (scene.py) и окна программы (overlay.py).
Повторяет программу из инструкции «КПП работает весь день»: лампа красная → ждём машину у датчика → лампа зелёная →
мотор по часовой 2 с (стрела вверх) → ждём 3 с → мотор против часовой 2 с (стрела вниз) → снова красная."""
import math

LOOP = 12.0
DETECT = 2.5            # датчик увидел машину
GREEN = (2.5, 2.7)      # блок «лампа зелёная»
DIR_UP = (2.7, 2.9)     # блок «направление: туда»
UP = (2.9, 4.9)         # мотор 2 с — стрела 0° → 90°
WAIT = (4.9, 7.9)       # ждать 3 с
DIR_DN = (7.9, 8.1)     # блок «направление: обратно»
DOWN = (8.1, 10.1)      # мотор 2 с — стрела 90° → 0°
RED = (10.1, 10.3)      # блок «лампа красная»
CAR_IN = 10.6           # следующая машина появляется слева (и доезжает до шлагбаума к 2,3 с следующей петли)
CAR_STOP = 2.3
CAR_GO = (5.0, 6.9)     # машина проезжает под стрелой и уезжает
RATIO = 24              # червяк — шестерня 24z: 24 оборота червяка на оборот стрелы

def _motor(u):          # мотор с червяком — почти равномерно, мягко на краях
    u = min(1.0, max(0.0, u))
    return 0.8 * u + 0.2 * (1 - math.cos(math.pi * u)) / 2

def boom(t):
    """Угол стрелы, градусы (0 — лежит на стойке, 90 — вертикально)."""
    t %= LOOP
    if t < UP[0]: return 0.0
    if t < UP[1]: return 90.0 * _motor((t - UP[0]) / (UP[1] - UP[0]))
    if t < DOWN[0]: return 90.0
    if t < DOWN[1]: return 90.0 * (1 - _motor((t - DOWN[0]) / (DOWN[1] - DOWN[0])))
    return 0.0

def worm(t):
    """Угол червяка, радианы: 24 оборота на оборот стрелы, после спуска — снова 0 (петля без шва)."""
    return math.radians(boom(t)) * RATIO

def lamp(t):
    """Цвет лампы на смартхабе: 'red' или 'green'."""
    t %= LOOP
    return 'green' if GREEN[0] <= t < RED[0] else 'red'

def moving(t):
    t %= LOOP
    return UP[0] <= t < UP[1] or DOWN[0] <= t < DOWN[1]

def blink(t, hz=3.0):
    """Жёлтые огни на стойке мигают, пока стрела движется."""
    return moving(t) and (t * hz) % 1.0 < 0.5

def block(t):
    """Номер блока программы, который сейчас выполняется (для подсветки в окне)."""
    t %= LOOP
    for k, (a, b) in ((4, GREEN), (5, DIR_UP), (6, UP), (7, WAIT), (8, DIR_DN), (9, DOWN), (2, RED)):
        if a <= t < b: return k
    return 3              # «ждать до расстояние < 10»

def car(t):
    """Положение машинки на сцене окна: 0 — левый край, 0.55 — стоит у шлагбаума, 1.1 — уехала за правый край.
    None — машинки нет."""
    t %= LOOP
    if t >= CAR_IN:                                   # въезд: 10,6 → 12,0 → (0 … 2,3) следующей петли
        u = (t - CAR_IN) / (LOOP - CAR_IN + CAR_STOP)
    elif t < CAR_STOP:
        u = (t + LOOP - CAR_IN) / (LOOP - CAR_IN + CAR_STOP)
    else:
        u = None
    if u is not None:
        return -0.2 + (0.55 + 0.2) * (1 - (1 - u) ** 2)   # подъезжает и тормозит
    if t < CAR_GO[0]: return 0.55
    if t < CAR_GO[1]:
        u = (t - CAR_GO[0]) / (CAR_GO[1] - CAR_GO[0])
        return 0.55 + (1.25 - 0.55) * u * u              # трогается и разгоняется
    return None
